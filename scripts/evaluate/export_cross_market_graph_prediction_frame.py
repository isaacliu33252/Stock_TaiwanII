#!/usr/bin/env python3
"""Export cross-market graph shadow daily prediction frame from a report.

Research-only helper. It expects reports generated by
evaluate_cross_market_directed_graph_shadow.py after the `prediction_frame`
field was added.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


DEFAULT_INPUT = PROJECT_ROOT / "results" / "cross_market_directed_graph_shadow_full_conditional_20260715.json"
DEFAULT_OUTPUT = PROJECT_ROOT / "results" / "cross_market_directed_graph_shadow_prediction_frame_latest.csv"


def _unwrap(payload: dict[str, Any]) -> dict[str, Any]:
    data = payload.get("data")
    return data if isinstance(data, dict) else payload


def export_prediction_frame(report_path: Path, output_path: Path) -> dict[str, Any]:
    payload = json.loads(report_path.read_text(encoding="utf-8"))
    report = _unwrap(payload)
    action_model = report.get("action_model") or {}
    records = action_model.get("prediction_frame") or []
    if not records:
        raise RuntimeError(
            "Report has no action_model.prediction_frame. Regenerate it with "
            "scripts/evaluate/evaluate_cross_market_directed_graph_shadow.py."
        )
    frame = pd.DataFrame(records)
    frame["date"] = pd.to_datetime(frame["date"]).dt.strftime("%Y-%m-%d")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(output_path, index=False, encoding="utf-8-sig")
    no_add = frame["no_add_active"].astype(bool)
    return {
        "report_path": str(report_path),
        "output_path": str(output_path),
        "rows": int(len(frame)),
        "start": str(frame["date"].iloc[0]) if len(frame) else None,
        "end": str(frame["date"].iloc[-1]) if len(frame) else None,
        "no_add_active_days": int(no_add.sum()),
        "mean_prob_no_add": float(frame["prob_NO_ADD"].mean()) if len(frame) else None,
        "mean_prob_reenter": float(frame["prob_REENTER"].mean()) if len(frame) else None,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", default=str(DEFAULT_INPUT))
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    args = parser.parse_args()
    summary = export_prediction_frame(Path(args.report), Path(args.output))
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
